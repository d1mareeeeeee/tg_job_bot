"""Дешёвый префильтр «вакансия / не вакансия» без обращения к LLM.

Задача — не жечь токены на постах, которые точно не вакансии (мемы, реклама,
объявления, новости). Порог намеренно мягкий: лучше пропустить сомнительный
пост в LLM, чем потерять реальную вакансию.
"""

from __future__ import annotations

# Сильные маркеры: одного достаточно, чтобы счесть пост вакансией.
STRONG_MARKERS = (
    "вакансия",
    "ваканс",
    "мы ищем",
    "ищем",
    "требуется",
    "требуются",
    "в команду",
    "зарплата",
    "зарплатная вилка",
    "зп от",
    "зп:",
    "оклад",
    "вилка",
    "релокация",
    "we are hiring",
    "we're hiring",
    "hiring",
    "looking for",
    "job opening",
    "vacancy",
    "открыта позиция",
    "открытая позиция",
)

# Слабые маркеры: сами по себе слабы, но два и более — уже сигнал.
WEAK_MARKERS = (
    "зп",
    "salary",
    "position",
    "удалёнка",
    "удаленка",
    "удалённо",
    "удаленно",
    "remote",
    "офис",
    "office",
    "гибрид",
    "hybrid",
    "grade",
    "грейд",
    "junior",
    "middle",
    "senior",
    "джуниор",
    "мидл",
    "синьор",
    "опыт от",
    "стек",
    "обязанности",
    "требования",
    "условия",
    "мы предлагаем",
    "что мы предлагаем",
    "график",
    "оформление",
    "full-time",
    "part-time",
    "фуллтайм",
    "занятость",
)

# Стоп-слова явной рекламы/розыгрышей — гасят срабатывание слабых маркеров.
SPAM_MARKERS = (
    "розыгрыш",
    "разыгрываем",
    "give away",
    "giveaway",
    "скидка",
    "промокод",
    "реферальная ссылка",
    "подпишись",
    "подпишитесь",
    "переходи по ссылке",
    "реклама",
    "#реклама",
    "erid",
)

# Минимальная длина осмысленного поста-вакансии.
MIN_LENGTH = 60


def looks_like_vacancy(text: str) -> bool:
    """Грубая эвристика: похоже ли на вакансию.

    Логика:
      * пустой/слишком короткий текст → False;
      * хотя бы один сильный маркер → True (даже при наличии рекламы —
        вакансии часто помечают #реклама);
      * иначе: считаем слабые маркеры; при явной рекламе требуем строже
        (>=3 слабых), без рекламы достаточно >=2.
    """
    if not text:
        return False

    lowered = text.lower()

    if len(text.strip()) < MIN_LENGTH:
        return False

    # Сильный маркер — сразу пропускаем в LLM.
    if any(marker in lowered for marker in STRONG_MARKERS):
        return True

    weak_hits = sum(1 for marker in WEAK_MARKERS if marker in lowered)
    is_spammy = any(marker in lowered for marker in SPAM_MARKERS)

    # Если пост выглядит рекламным — требуем больше сигналов вакансии.
    threshold = 3 if is_spammy else 2
    return weak_hits >= threshold
