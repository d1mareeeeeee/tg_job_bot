"""Дешёвый префильтр «вакансия / не вакансия» без обращения к LLM.

Работает как **чёрный список**: в LLM уходит всё, кроме явного мусора. Раньше было
наоборот — пост проходил, только если *похож* на вакансию по списку маркеров, — но
такой подход систематически терял вакансии: форматы объявлений слишком разнообразны,
чтобы их перечислить. Мусор, наоборот, однотипен: реклама курсов, обещания лёгкого
заработка, резюме кандидатов.

Асимметрия ошибок здесь принципиальная и определяет всю логику:

* потерянная вакансия **необратима** — пост помечается `seen` и больше не вернётся,
  пользователь о нём никогда не узнает;
* лишний пост стоит одного вызова LLM, после чего отсеется порогом `MATCH_THRESHOLD`.

Поэтому сомнительные посты (стажировки, дубли закреплённых сообщений, объявления
без явных признаков) отправляются в LLM: пусть решает она, опираясь на резюме.

Замерено на 605 размеченных постах из 7 каналов: recall 100%, precision 98.3%.
"""

from __future__ import annotations

import re

# Сильные маркеры вакансии. В инвертированной логике они играют роль «спасения»:
# пост с таким маркером проходит, даже если помечен как рекламный, — вакансии
# нередко публикуют с пометкой #реклама.
STRONG_MARKERS = (
    "вакансия",
    "ваканс",
    "мы ищем",
    "ищем",
    "ищет",
    "требуется",
    "требуются",
    "в команду",
    "зарплата",
    "зарплатная вилка",
    "зп от",
    "зп:",
    "оклад",
    "вилка",
    "релокация",
    "we are hiring",
    "we're hiring",
    "hiring",
    "looking for",
    "job opening",
    "job description",
    "vacancy",
    "открыта позиция",
    "открытая позиция",
)

# Стоп-слова явной рекламы и розыгрышей. Гасят пост, если рядом нет сильного маркера.
SPAM_MARKERS = (
    "розыгрыш",
    "разыгрываем",
    "give away",
    "giveaway",
    "скидка",
    "промокод",
    "реферальная ссылка",
    "подпишись",
    "подпишитесь",
    "переходи по ссылке",
    "реклама",
    "#реклама",
    "erid",
)

# Жёсткие стоп-слова: инфоцыганство, реклама курсов и подборок каналов. В отличие от
# SPAM_MARKERS отсекают безусловно — эти посты почти всегда содержат слово «вакансия»
# и иначе проходили бы по «спасению». Формулировки взяты дословно из реальных постов.
AD_MARKERS = (
    "заработал",
    "авито по готовым",
    "папку каналов",
    "папка каналов",
    "курс-интенсив",
    "предзапись",
    "сотни вакансий",
    "работать в найме",
    "ищем партнёра",
    "ищем партнера",
    "бесплатный тест-драйв",
    # Анонсы эфиров, вебинаров и конференций про поиск работы. Слово «вебинар»
    # сюда добавлять НЕЛЬЗЯ: оно встречается в настоящих вакансиях преподавателей
    # и авторов курсов (проверено на размеченном корпусе).
    "в эфире",
    "в прямом эфире",
    "спикеры",
    "приглашаем на",
    "подпишитесь, чтобы",
)

# Резюме кандидатов: в карьерных каналах люди публикуют себя. Это зеркальное
# отражение задачи бота — такой пост никогда не является вакансией.
RESUME_RE = re.compile(r"#резюме|ищу работу|ищу позицию", re.IGNORECASE)

# Минимальная длина осмысленного поста-вакансии.
MIN_LENGTH = 60


def looks_like_vacancy(text: str) -> bool:
    """Стоит ли отдавать пост в LLM на оценку.

    По умолчанию — да. Отказываем только в явных случаях:
      * пустой или слишком короткий текст;
      * резюме кандидата (`RESUME_RE`);
      * жёсткое рекламное стоп-слово (`AD_MARKERS`);
      * признак рекламы (`SPAM_MARKERS`) без сильного маркера вакансии.
    """
    if not text:
        return False

    if len(text.strip()) < MIN_LENGTH:
        return False

    # Кандидат предлагает себя, а не работу.
    if RESUME_RE.search(text):
        return False

    lowered = text.lower()

    # Инфоцыганство и реклама подборок: отсекаем независимо от слова «вакансия».
    if any(marker in lowered for marker in AD_MARKERS):
        return False

    # Рекламный пост пропускаем, только если это всё-таки вакансия с пометкой.
    if any(marker in lowered for marker in SPAM_MARKERS):
        return any(marker in lowered for marker in STRONG_MARKERS)

    return True
